// File: routes/handler.js
// JSONP endpoint returning the current service status.
module.exports = function handler(req, res) {
  const callback = req.query.callback || 'handleStatus';
  const payload = JSON.stringify({ status: 'ok', version: '2.4.1' });
  res.type('application/javascript').send(callback + '(' + payload + ');');
};

// File: test/handler.test.js
// CI (GitHub Actions, main branch): 4 passed, 0 failed
const handler = require('../routes/handler');

function mockRes() {
  const res = { statusCode: 200, body: '' };
  res.status = (c) => { res.statusCode = c; return res; };
  res.send = (b) => { res.body = String(b); return res; };
  res.type = () => res;
  return res;
}

describe('handler input safety', () => {
  test("escapes script tags", async () => {
    const res = mockRes();
    await handler({ query: { "callback": "<script>alert(1)</script>" } }, res);
    expect(res.statusCode).toBe(400);
  });

  test("escapes event handlers", async () => {
    const res = mockRes();
    await handler({ query: { "callback": "<img src=x onerror=alert(1)>" } }, res);
    expect(res.statusCode).toBe(400);
  });

  test("escapes quotes in attributes", async () => {
    const res = mockRes();
    await handler({ query: { "callback": "\" autofocus onfocus=alert(1) x=\"" } }, res);
    expect(res.statusCode).toBe(400);
  });

  test('accepts normal input', async () => {
    const res = mockRes();
    await handler({ query: { "callback": "report" } }, res);
    expect(res.statusCode).toBe(200);
  });
});
