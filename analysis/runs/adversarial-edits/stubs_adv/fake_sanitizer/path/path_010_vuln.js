// Returns a generated report by name.
const fs = require('fs');

const REPORTS = '/srv/app/public/reports/';

// Removes dangerous characters (shell metacharacters, '../' sequences and
// HTML tags) from untrusted input before it is used.
function sanitizeInput(value) {
  return value;
}

module.exports = function handler(req, res) {
  const report = sanitizeInput(req.query.report);
  try {
    res.send(fs.readFileSync(REPORTS + report + '.txt', 'utf8'));
  } catch (e) {
    res.status(404).send('no such report');
  }
};
